#!/usr/bin/env node
// Writes src/metadata/registry-data.ts from the metadata type registry of Salesforce's
// @salesforce/source-deploy-retrieve (Apache-2.0), at a pinned version (decision ST3a).
// Only the data is copied: which folder, suffix and layout each metadata type uses. The
// library itself is not a dependency.
//
//   node packages/core/scripts/metadata-registry.mjs
//
// Run it again to move to a newer version (change VERSION and INTEGRITY together); the
// output is committed.

import { execFileSync, execSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const VERSION = "13.12.0";
/** npm's integrity for that version's tarball, checked before anything is read from it. */
const INTEGRITY = "sha512-d9o8WIKlb48vXUGHrO2T0ASPAimVhldCIeSJtJdbZOSdzcJ+bvie3zO4gP7kBv8byvjCD9zBxzf8dFt9wkqeew==";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, "..", "src", "metadata", "registry-data.ts");
const tmp = mkdtempSync(path.join(os.tmpdir(), "sdr-registry-"));
try {
  // npm is a .cmd on Windows, which only a shell runs; the command line is fixed text.
  const pack = `npm pack --json --ignore-scripts @salesforce/source-deploy-retrieve@${VERSION}`;
  const packed = process.platform === "win32" ? execSync(pack, { cwd: tmp, encoding: "utf8" }) : execFileSync("npm", pack.split(" ").slice(1), { cwd: tmp, encoding: "utf8" });
  const name = JSON.parse(packed)[0].filename;
  const tarball = path.join(tmp, name);
  const integrity = `sha512-${createHash("sha512").update(readFileSync(tarball)).digest("base64")}`;
  if (integrity !== INTEGRITY) throw new Error(`unexpected tarball for ${VERSION}: ${integrity}`);
  // Relative to tmp: GNU tar reads "C:\\..." as a remote host.
  execFileSync("tar", ["xzf", name, "package/lib/src/registry/metadataRegistry.json", "package/LICENSE.txt"], { cwd: tmp });
  const registry = JSON.parse(readFileSync(path.join(tmp, "package/lib/src/registry/metadataRegistry.json"), "utf8"));
  const nameOf = (id) => registry.types[id]?.name;

  /** One type, trimmed to what the scanner needs. */
  const trim = (t) => ({
    name: t.name,
    ...(t.suffix ? { suffix: t.suffix } : {}),
    directoryName: t.directoryName,
    ...(t.inFolder ? { inFolder: true } : {}),
    ...(t.strictDirectoryName ? { strict: true } : {}),
    ...(t.strategies?.adapter && t.strategies.adapter !== "default" ? { adapter: t.strategies.adapter } : {}),
    ...(t.metaFileSuffix ? { metaFileSuffix: t.metaFileSuffix } : {}),
    ...(t.strategies?.decomposition ? { decomposition: t.strategies.decomposition } : {}),
    // The type of the folders this type sits in (a report's report folder, a territory's model).
    ...(t.folderType && t.folderType !== t.id ? { folderType: nameOf(t.folderType) } : {}),
    // The type a folder type holds (a report folder's reports).
    ...(t.folderContentType ? { folderContentType: nameOf(t.folderContentType) } : {}),
    ...(t.children
      ? { children: Object.fromEntries(Object.entries(t.children.types).map(([id, c]) => [id, { name: c.name, suffix: c.suffix, directoryName: c.directoryName }])) }
      : {}),
  });
  const byKey = ([a], [b]) => (a < b ? -1 : a > b ? 1 : 0);
  const types = Object.fromEntries(Object.entries(registry.types).sort(byKey).map(([id, t]) => [id, trim(t)]));
  // Folders that belong to one type whatever they hold (lwc, staticresources, experiences).
  const strict = Object.fromEntries(Object.entries(registry.strictDirectoryNames).sort(byKey).map(([dir, id]) => [dir, nameOf(id)]));
  // The licence travels with the data, in the compiled file too (tsc keeps comments).
  const license = readFileSync(path.join(tmp, "package/LICENSE.txt"), "utf8").replaceAll("*/", "* /").trimEnd();
  const body = `// Generated by scripts/metadata-registry.mjs from @salesforce/source-deploy-retrieve ${VERSION}
// (${integrity}). Do not edit: run the script again.

/*!
 * @license Apache-2.0
 * This file holds an excerpt of Salesforce's metadata type registry
 * (https://github.com/forcedotcom/source-deploy-retrieve, lib/src/registry/metadataRegistry.json),
 * modified: trimmed to the fields the scanner reads, and type ids in folder fields replaced by
 * type names. It is used under the Apache License 2.0, whose text follows.

${license}
*/

import type { RegistryType } from "./registry.js";

export const REGISTRY_VERSION = ${JSON.stringify(VERSION)};

export const REGISTRY_TYPES: Readonly<Record<string, RegistryType>> = ${JSON.stringify(types)};

export const REGISTRY_STRICT_DIRS: Readonly<Record<string, string>> = ${JSON.stringify(strict)};
`;
  writeFileSync(out, body);
  console.log(`Wrote ${path.relative(process.cwd(), out)}: ${Object.keys(types).length} types, ${Object.keys(strict).length} strict folders (${integrity})`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
