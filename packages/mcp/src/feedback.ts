// Feedback (phase 5, AR4): whether published stories were accepted. The Jira diff reads each
// published story back from Jira and compares it with what was published, in memory: Jira's
// text is never stored or returned, only how much changed. Its guess is recorded for the
// review page and the report, where people's verdicts take precedence.

import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { adfToText, AtlassianError, type AtlassianClient, type JiraStory } from "@sf-agent-po/connectors";
import type { ContextRepository, FeedbackInput, FeedbackRepository, JiraDiffValue, Masker, WorkflowRepository } from "@sf-agent-po/core";
import { z } from "zod";
import { type ArtifactMeta, getArtifact, type SentStory } from "./artifacts.js";
import { allStories, type Backlog, storyDescription } from "./backlog.js";
import type { CallContext } from "./review.js";

type Text = { content: { type: "text"; text: string }[] };
const text = (t: string): Text => ({ content: [{ type: "text", text: t }] });

export interface FeedbackKit {
  contexts: ContextRepository;
  masker: Masker;
  feedback: FeedbackRepository;
  atlassian?: () => AtlassianClient;
  workflows?: WorkflowRepository;
  guard: <A extends { context?: string }>(fn: (args: A, call: CallContext) => Promise<Text>) => (args: A, call: CallContext) => Promise<Text & { isError?: boolean }>;
  contextName: z.ZodDefault<z.ZodString>;
}

/** D2: an edit is major past this share of the words changed (or a criterion added or removed). A context setting can change it. */
export const DEFAULT_MAJOR_SHARE = 0.3;
/** The success measure's target: stories accepted without major edits. */
export const TARGET_ACCEPTED = 0.9;
/** Words compared per story: a longer description is compared on its first words. */
const MAX_WORDS = 3_000;
/** Jira reads in flight. */
const PARALLEL = 4;

/** The words of a text, for comparing: letters and digits, lower case. */
export function words(text: string): string[] {
  return (text.toLowerCase().match(/[\p{L}\p{N}]+/gu) ?? []).slice(0, MAX_WORDS);
}

/** The share of words changed between two texts: 0 when they have the same words in the same order, 1 when none is kept. */
export function changedShare(a: readonly string[], b: readonly string[]): number {
  if (!a.length && !b.length) return 0;
  // Longest common subsequence, one row at a time.
  let prev = new Uint16Array(b.length + 1);
  let row = new Uint16Array(b.length + 1);
  for (let i = 1; i <= a.length; i++) {
    for (let j = 1; j <= b.length; j++) row[j] = a[i - 1] === b[j - 1] ? prev[j - 1]! + 1 : Math.max(prev[j]!, row[j - 1]!);
    [prev, row] = [row, prev];
  }
  return 1 - (2 * prev[b.length]!) / (a.length + b.length);
}

/** A description without what the publisher adds at its end (the sources and the "Generated by" line). */
export function storyBody(text: string): string {
  const ends = [text.search(/^#{1,6} Sources\s*$/m), text.search(/^Generated by sf-agent-po\b/m)].filter((i) => i >= 0);
  return ends.length ? text.slice(0, Math.min(...ends)) : text;
}

/** How many acceptance criteria a description lists: the items under its "Acceptance criteria" heading. */
export function criteriaCount(text: string): number {
  const lines = text.split("\n");
  const start = lines.findIndex((l) => /^#{1,6}\s*acceptance criteria\s*$/i.test(l.trim()));
  if (start < 0) return 0;
  let n = 0;
  for (const l of lines.slice(start + 1)) {
    if (/^#{1,6}\s/.test(l.trim())) break;
    if (/^\s*(?:-|\*|\d+[.)])\s+\S/.test(l)) n++;
  }
  return n;
}

export interface StoryDiff {
  value: Exclude<JiraDiffValue, "deleted">;
  changedShare: number;
  criteria: [number, number];
  points?: [number | undefined, number | undefined];
}

/**
 * Compares a story as published with Jira's, both in clear (in memory only). Major (D2): more
 * than `majorShare` of the words of the summary and description changed, or a criterion added
 * or removed. Minor: anything else that changed, story points included.
 */
export function compareStory(sent: { summary: string; text: string; points?: number }, now: { summary: string; text: string; points?: number }, majorShare = DEFAULT_MAJOR_SHARE): StoryDiff {
  const before = storyBody(sent.text);
  const after = storyBody(now.text);
  const share = changedShare(words(`${sent.summary}\n${before}`), words(`${now.summary}\n${after}`));
  const criteria: [number, number] = [criteriaCount(before), criteriaCount(after)];
  const pointsChanged = now.points !== undefined && now.points !== sent.points;
  const value = share > majorShare || criteria[0] !== criteria[1] ? "major" : share > 0 || pointsChanged ? "minor" : "unchanged";
  return { value, changedShare: Math.round(share * 100) / 100, criteria, ...(pointsChanged && { points: [sent.points, now.points] }) };
}

/** The context's model label (a setting: MCP does not say which model a host runs), if set. */
export function modelLabel(contexts: ContextRepository, context: string): string | undefined {
  const m = contexts.get(context)?.settings.model;
  return typeof m === "string" && m.trim() ? m.trim() : undefined;
}

/** The share of words past which an edit is major, from the context's settings. */
export function majorShare(contexts: ContextRepository, context: string): number {
  const v = contexts.get(context)?.settings.majorEditShare;
  return typeof v === "number" && v > 0 && v < 1 ? v : DEFAULT_MAJOR_SHARE;
}

/** The guided workflow that saved an artifact, from the runs of its context. */
export function workflowOf(runs: WorkflowRepository | undefined, context: string, artifactId: string): string | undefined {
  for (const run of runs?.list(context, { limit: 100 }) ?? []) {
    if (run.steps.some((s) => (s.answer as { artifactId?: unknown } | undefined)?.artifactId === artifactId)) return run.workflow;
  }
  return undefined;
}

const pct = (n: number) => `${Math.round(n * 100)}%`;

export function registerFeedbackTools(server: McpServer, kit: FeedbackKit): void {
  const { contexts, masker, guard, contextName } = kit;

  server.registerTool(
    "feedback_jira_diff",
    {
      title: "Compare published stories with Jira",
      description:
        "Reads each story of a backlog published to Jira back from Jira and compares it with what was published: unchanged, minor edit, major edit (more than 30% of the words changed, " +
        "or an acceptance criterion added or removed) or deleted. Records the result as feedback, the guess the review page starts from. Jira's text is never returned, only how much changed. " +
        "Run it once the team has worked on the stories.",
      inputSchema: {
        context: contextName,
        artifactId: z.string().describe("Id of the published backlog artifact."),
        storyPointsField: z.string().regex(/^customfield_\d+$/).optional().describe("The story points field, when it was not given at publish."),
        model: z.string().min(1).max(80).optional().describe('The model that wrote the backlog, e.g. "Opus 5.5 on Copilot", kept as the context\'s model label for the report.'),
        majorEditShare: z.number().gt(0).lt(1).optional().describe("Share of words changed past which an edit is major; kept as the context's setting. Default 0.3."),
      },
      annotations: { readOnlyHint: false, openWorldHint: true },
    },
    guard(async ({ context, artifactId, storyPointsField, model, majorEditShare }: { context: string; artifactId: string; storyPointsField?: string; model?: string; majorEditShare?: number }) => {
      if (!kit.atlassian) throw new Error("Jira is not set up for this server.");
      const doc = getArtifact(contexts, context, artifactId);
      const meta = doc.metadata as ArtifactMeta & { backlog?: Backlog };
      if (doc.kind !== "backlog" || !meta.backlog) throw new Error(`${artifactId} is not a backlog artifact.`);
      const mapping = meta.jira;
      if (!mapping || !Object.keys(mapping.items).length) throw new Error(`Backlog ${artifactId} has not been published to Jira yet.`);
      if (model !== undefined || majorEditShare !== undefined) contexts.updateSettings(context, { ...(model !== undefined && { model: model.trim() }), ...(majorEditShare !== undefined && { majorEditShare }) });
      const threshold = majorShare(contexts, context);
      const backlog = meta.backlog;
      // Published before the diff kept what was sent: the backlog is that version when it was not saved again since.
      const sameAsPublished = meta.status === "published" && mapping.publishedVersion === meta.version;
      const titles = new Map(contexts.documents(context).filter((d) => d.masked).map((d) => [d.id, d.title]));
      const pointsField = storyPointsField ?? mapping.storyPointsField;
      const client = kit.atlassian();
      const label = modelLabel(contexts, context);
      const workflow = workflowOf(kit.workflows, context, artifactId);

      const stories = allStories(backlog).filter(({ story }) => mapping.items[story.id]);
      const rows: { id: string; key: string; summary: string; line: string; value?: JiraDiffValue }[] = [];
      const results = await mapAll(stories, PARALLEL, async ({ story }) => {
        const entry = mapping.items[story.id]!;
        const sent: SentStory | undefined =
          entry.sent ??
          (sameAsPublished ? { summary: story.summary, text: adfToText(storyDescription(story, backlog, titles)), ...(story.storyPoints !== undefined && { points: story.storyPoints }) } : undefined);
        if (!sent) return { story, key: entry.key, skipped: "published before the diff kept what was sent, and the backlog was saved again since: publish it again to compare" };
        let now: JiraStory | undefined;
        try {
          now = await client.getStory(entry.key, pointsField);
        } catch (err) {
          return { story, key: entry.key, skipped: err instanceof AtlassianError ? `Jira refused to read it (HTTP ${err.status})` : "Jira could not be read" };
        }
        if (!now) return { story, key: entry.key, deleted: true as const };
        // Both in clear, in memory only: the published text with its real values put back, and Jira's.
        const real = (t: string) => masker.unmask(context, t).text;
        const diff = compareStory({ summary: real(sent.summary), text: real(sent.text), ...(sent.points !== undefined && { points: sent.points }) }, { summary: now.summary, text: adfToText(now.description), ...(now.points !== undefined && { points: now.points }) }, threshold);
        const status = now.status ? (await masker.mask(context, now.status)).text : undefined;
        return { story, key: entry.key, diff, status };
      });

      const record: FeedbackInput[] = [];
      for (const r of results) {
        const base = { id: r.story.id, key: r.key, summary: r.story.summary };
        if ("skipped" in r && r.skipped) {
          rows.push({ ...base, line: `not compared: ${r.skipped}` });
          continue;
        }
        const value: JiraDiffValue = "deleted" in r ? "deleted" : r.diff!.value;
        const d = "diff" in r ? r.diff : undefined;
        const facts = d
          ? [
              d.changedShare ? `${pct(d.changedShare)} of the words changed` : "",
              d.criteria[0] !== d.criteria[1] ? `acceptance criteria ${d.criteria[0]} → ${d.criteria[1]}` : "",
              d.points ? `story points ${d.points[0] ?? "none"} → ${d.points[1] ?? "none"}` : "",
              r.status ? `status ${r.status}` : "",
            ].filter(Boolean)
          : [];
        const word = value === "deleted" ? "deleted in Jira" : value === "unchanged" ? "unchanged" : `${value} edit`;
        rows.push({ ...base, value, line: `${word}${facts.length ? ` (${facts.join(", ")})` : ""}` });
        record.push({
          context,
          artifact: artifactId,
          item: r.story.id,
          kind: "jira_diff",
          value,
          ...(label && { model: label }),
          ...(workflow && { workflow }),
          details: { key: r.key, ...(d && { changedShare: d.changedShare, criteria: d.criteria, ...(d.points && { points: d.points }) }), ...(r.status && { status: r.status }), majorEditShare: threshold },
        });
      }
      kit.feedback.record(record);

      const n = (v: JiraDiffValue) => rows.filter((r) => r.value === v).length;
      const compared = rows.filter((r) => r.value).length;
      const kept = compared - n("major") - n("deleted");
      const head = [
        `Jira diff of "${doc.title}" in project ${mapping.projectKey}: ${compared} of ${rows.length} published stories compared${label ? `, model label "${label}"` : ""}.`,
        `${n("unchanged")} unchanged, ${n("minor")} minor edit(s), ${n("major")} major edit(s), ${n("deleted")} deleted (major: more than ${pct(threshold)} of the words changed, or a criterion added or removed).`,
        ...(compared ? [`So far ${kept} of ${compared} (${pct(kept / compared)}) show no major edit, against the ${pct(TARGET_ACCEPTED)} target. This is a guess: people's verdicts on the review page take precedence.`] : []),
      ];
      const parts = [head.join("\n"), rows.map((r) => `- ${r.id} ${r.key} "${r.summary}": ${r.line}`).join("\n")];
      if (!label) parts.push('No model label is set for this context: pass model (e.g. "Opus 5.5 on Copilot") so the report can compare models.');
      return text(parts.join("\n\n"));
    }),
  );
}

/** Runs `fn` over `items` with at most `limit` calls in flight, keeping the order. */
async function mapAll<T, R>(items: readonly T[], limit: number, fn: (item: T) => Promise<R>): Promise<R[]> {
  const out: R[] = new Array(items.length);
  let next = 0;
  await Promise.all(
    Array.from({ length: Math.min(limit, items.length) }, async () => {
      while (next < items.length) {
        const i = next++;
        out[i] = await fn(items[i]!);
      }
    }),
  );
  return out;
}
