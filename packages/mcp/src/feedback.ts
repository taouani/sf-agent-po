// Feedback (phase 5, AR4): whether published stories were accepted. The Jira diff reads each
// published story back from Jira and compares it with what was published, in memory: Jira's
// text is never stored or returned, only how much changed. Its guess is recorded for the
// review page and the report, where people's verdicts take precedence.

import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { adfToText, AtlassianError, type AtlassianClient, type JiraStory } from "@sf-agent-po/connectors";
import { type ContextRepository, type FeedbackInput, type FeedbackRepository, type JiraDiffValue, type Masker, MAX_PUBLISHED_TEXT, type PublishedStory, type WorkflowRepository } from "@sf-agent-po/core";
import { z } from "zod";
import { type ArtifactMeta, getArtifact } from "./artifacts.js";
import type { Backlog, Story } from "./backlog.js";
import { itemHash, labelsFor, oneLine, storyFields } from "./jira.js";
import type { CallContext } from "./review.js";

type Text = { content: { type: "text"; text: string }[] };
const text = (t: string): Text => ({ content: [{ type: "text", text: t }] });

export interface FeedbackKit {
  contexts: ContextRepository;
  masker: Masker;
  feedback: FeedbackRepository;
  atlassian?: () => AtlassianClient;
  workflows?: WorkflowRepository;
  guard: <A extends { context?: string }>(fn: (args: A, call: CallContext) => Promise<Text>) => (args: A, call: CallContext) => Promise<Text & { isError?: boolean }>;
  contextName: z.ZodDefault<z.ZodString>;
}

/** D2: an edit is major past this share of the words changed (or a criterion added or removed). A context setting can change it. */
export const DEFAULT_MAJOR_SHARE = 0.3;
/** The success measure's target: stories accepted without major edits. */
export const TARGET_ACCEPTED = 0.9;
/** Words compared per story: a longer description is compared on its first words. Keep it under 65,536: the comparison counts in 16 bits. */
const MAX_WORDS = 3_000;

const segmenter = new Intl.Segmenter(undefined, { granularity: "word" });

/** The words of a text, for comparing: lower case, NFC, split as the language's words (Chinese and Japanese too). */
export function words(text: string): string[] {
  const out: string[] = [];
  for (const s of segmenter.segment(text.normalize("NFC").toLowerCase())) {
    if (s.isWordLike) out.push(s.segment);
    if (out.length >= MAX_WORDS) break;
  }
  return out;
}

/** The share of words changed between two texts: 0 when they have the same words in the same order, 1 when none is kept. */
export function changedShare(a: readonly string[], b: readonly string[]): number {
  if (!a.length && !b.length) return 0;
  // Longest common subsequence, one row at a time.
  let prev = new Uint16Array(b.length + 1);
  let row = new Uint16Array(b.length + 1);
  for (let i = 1; i <= a.length; i++) {
    for (let j = 1; j <= b.length; j++) row[j] = a[i - 1] === b[j - 1] ? prev[j - 1]! + 1 : Math.max(prev[j]!, row[j - 1]!);
    [prev, row] = [row, prev];
  }
  return 1 - (2 * prev[b.length]!) / (a.length + b.length);
}

/** A description without what the publisher adds at its end: from its last "Sources" heading, or its "Generated by" line. */
export function storyBody(text: string): string {
  const sources = [...text.matchAll(/^#{1,6} Sources\s*$/gm)].at(-1)?.index;
  const generated = text.search(/^Generated by sf-agent-po\b/m);
  const ends = [sources ?? -1, generated].filter((i) => i >= 0);
  return ends.length ? text.slice(0, Math.min(...ends)) : text;
}

type Adf = { type?: string; text?: string; content?: Adf[] };
const adfPlain = (n: Adf): string => (n.text ?? "") + (n.content ?? []).map(adfPlain).join("");

/**
 * How many acceptance criteria a Jira description lists: the items of the first list after its
 * "Acceptance criteria" heading (or a paragraph saying only that), not their sub-items.
 * Undefined when there is no such heading: the team rewrote the description another way.
 */
export function criteriaInAdf(doc: unknown): number | undefined {
  const nodes = ((doc as Adf | undefined)?.content ?? []) as Adf[];
  const start = nodes.findIndex((n) => (n.type === "heading" || n.type === "paragraph") && /^acceptance criteria\s*:?$/i.test(adfPlain(n).trim()));
  if (start < 0) return undefined;
  for (const n of nodes.slice(start + 1)) {
    if (n.type === "heading") break;
    if (n.type === "orderedList" || n.type === "bulletList" || n.type === "taskList") return (n.content ?? []).filter((c) => c.type === "listItem" || c.type === "taskItem").length;
  }
  return 0;
}

export interface StoryDiff {
  value: Exclude<JiraDiffValue, "deleted">;
  changedShare: number;
  /** As sent, and as Jira has them now (undefined: no "Acceptance criteria" heading left). */
  criteria: [number, number | undefined];
  points?: [number, number];
}

/** A story as it was sent, or as Jira holds it, in clear. */
export interface StoryText {
  summary: string;
  text: string;
  criteria?: number;
  points?: number;
}

/**
 * Compares a story as published with Jira's, both in clear (in memory only). Major (D2): more
 * than `majorShare` of the words of the summary and description changed, or a criterion added
 * or removed. Minor: anything else that changed, story points included when both sides have
 * them.
 */
export function compareStory(sent: StoryText & { criteria: number }, now: StoryText, majorShare = DEFAULT_MAJOR_SHARE): StoryDiff {
  const share = changedShare(words(`${sent.summary}\n${storyBody(sent.text)}`), words(`${now.summary}\n${storyBody(now.text)}`));
  const criteria: [number, number | undefined] = [sent.criteria, now.criteria];
  const criteriaChanged = now.criteria !== undefined && now.criteria !== sent.criteria;
  const pointsChanged = sent.points !== undefined && now.points !== undefined && now.points !== sent.points;
  const value = share > majorShare || criteriaChanged ? "major" : share > 0 || pointsChanged ? "minor" : "unchanged";
  return { value, changedShare: Math.round(share * 100) / 100, criteria, ...(pointsChanged && { points: [sent.points!, now.points!] }) };
}

/** The context's model label (a setting: MCP does not say which model a host runs), if set. */
export function modelLabel(contexts: ContextRepository, context: string): string | undefined {
  const m = contexts.get(context)?.settings.model;
  return typeof m === "string" && m.trim() ? m.trim() : undefined;
}

/** The share of words past which an edit is major, from the context's settings. */
export function majorShare(contexts: ContextRepository, context: string): number {
  const v = contexts.get(context)?.settings.majorEditShare;
  return typeof v === "number" && v > 0 && v < 1 ? v : DEFAULT_MAJOR_SHARE;
}

/** The guided workflow that saved an artifact, from the runs of its context. */
export function workflowOf(runs: WorkflowRepository | undefined, context: string, artifactId: string): string | undefined {
  for (const run of runs?.list(context, { limit: 100 }) ?? []) {
    if (run.steps.some((s) => (s.answer as { artifactId?: unknown } | undefined)?.artifactId === artifactId)) return run.workflow;
  }
  return undefined;
}

const pct = (n: number) => `${Math.round(n * 100)}%`;
const STATUS: Record<string, string> = { new: "to do", indeterminate: "in progress", done: "done" };

export function registerFeedbackTools(server: McpServer, kit: FeedbackKit): void {
  const { contexts, masker, guard, contextName } = kit;

  server.registerTool(
    "feedback_jira_diff",
    {
      title: "Compare published stories with Jira",
      description:
        "Reads each story of a backlog published to Jira back from Jira and compares it with what was published: unchanged, minor edit, major edit (by default more than 30% of the words changed, " +
        "or an acceptance criterion added or removed) or deleted. Records the result as feedback, the guess the review page starts from. Jira's text is never returned, only how much changed. " +
        "Run it once the team has worked on the stories.",
      inputSchema: {
        context: contextName,
        artifactId: z.string().describe("Id of the published backlog artifact."),
        storyPointsField: z.string().regex(/^customfield_\d+$/).optional().describe("The story points field, for stories published before the server kept which one was used."),
        model: z.string().min(1).max(80).optional().describe('The model that wrote the backlog, e.g. "Opus 5.5 on Copilot", kept as the context\'s model label for the report.'),
        majorEditShare: z.number().gt(0).lt(1).optional().describe("Share of words changed past which an edit is major; kept as the context's setting. Default 0.3."),
      },
      annotations: { readOnlyHint: false, openWorldHint: true },
    },
    guard(async ({ context, artifactId, storyPointsField, model, majorEditShare }: { context: string; artifactId: string; storyPointsField?: string; model?: string; majorEditShare?: number }) => {
      if (!kit.atlassian) throw new Error("Jira is not set up for this server.");
      const doc = getArtifact(contexts, context, artifactId);
      const meta = doc.metadata as ArtifactMeta & { backlog?: Backlog };
      if (doc.kind !== "backlog" || !meta.backlog) throw new Error(`${artifactId} is not a backlog artifact.`);
      const mapping = meta.jira;
      if (!mapping || !Object.keys(mapping.items).length) throw new Error(`Backlog ${artifactId} has not been published to Jira yet.`);
      const client = kit.atlassian();
      // A login that cannot see the project would read every story as deleted: checked first.
      await client.getProject(mapping.projectKey).catch((err: unknown) => {
        throw new Error(`Jira refused to show project ${mapping.projectKey}${err instanceof AtlassianError ? ` (HTTP ${err.status})` : ""}: check that the login can browse it. Nothing was recorded.`);
      });
      if (model !== undefined || majorEditShare !== undefined) contexts.updateSettings(context, { ...(model !== undefined && { model: model.trim() }), ...(majorEditShare !== undefined && { majorEditShare }) });
      const threshold = majorShare(contexts, context);
      const backlog = meta.backlog;
      const titles = new Map(contexts.documents(context).filter((d) => d.masked).map((d) => [d.id, d.title]));
      const label = modelLabel(contexts, context);
      const workflow = workflowOf(kit.workflows, context, artifactId);
      const sentBefore = kit.feedback.sent(context, artifactId);

      // Won't-have stories are not in Jira any more as far as the backlog goes: not compared.
      const stories = backlog.epics.flatMap((epic) => (epic.priority === "wont" ? [] : epic.stories.filter((s) => s.priority !== "wont" && mapping.items[s.id])));
      type Planned = { story: Story; key: string; sent?: Omit<PublishedStory, "context" | "artifact" | "sentAt">; why?: string };
      const planned: Planned[] = stories.map((story) => {
        const entry = mapping.items[story.id]!;
        const kept = sentBefore.get(story.id);
        if (kept) return { story, key: entry.key, sent: kept };
        // Published before the server kept what it sent: rebuilt from the backlog, and used only
        // when its hash is the one recorded at publish, which proves it is what was sent.
        for (const field of [undefined, storyPointsField]) {
          const fields = storyFields(story, backlog, titles, field);
          if (entry.hash && itemHash(fields, labelsFor(story, story.type === "spike" ? ["spike"] : [])) === entry.hash) {
            const text = adfToText(fields.description);
            return {
              story,
              key: entry.key,
              sent: { item: story.id, artifactVersion: mapping.publishedVersion ?? meta.version, issueKey: entry.key, summary: story.summary, text: text.slice(0, MAX_PUBLISHED_TEXT), truncated: text.length > MAX_PUBLISHED_TEXT, criteria: story.acceptanceCriteria.length, ...(field && story.storyPoints && { points: story.storyPoints, pointsField: field }) },
            };
          }
        }
        return { story, key: entry.key, why: "what was sent is not known (published by an earlier version, and changed since): publish it again to compare" };
      });

      // Jira, 100 stories per call, by the points field each was sent with.
      const now = new Map<string, JiraStory>();
      const failed = new Map<string, string>();
      const byField = new Map<string, Planned[]>();
      for (const p of planned.filter((p) => p.sent)) byField.set(p.sent!.pointsField ?? "", [...(byField.get(p.sent!.pointsField ?? "") ?? []), p]);
      for (const [field, group] of byField) {
        try {
          for (const [k, v] of await client.getStories(group.map((p) => p.key), field || undefined)) now.set(k, v);
        } catch (err) {
          for (const p of group) failed.set(p.story.id, err instanceof AtlassianError ? `Jira refused to read it (HTTP ${err.status})` : "Jira could not be read");
        }
      }
      const read = planned.filter((p) => p.sent && !failed.has(p.story.id));
      if (read.length > 1 && read.every((p) => !now.has(p.key))) {
        throw new Error(`Jira returned none of the ${read.length} published stories of project ${mapping.projectKey}: check that the login can see them. Nothing was recorded.`);
      }
      // Published again while this ran: compared with what is no longer the latest, so left out.
      const sentAfter = kit.feedback.sent(context, artifactId);
      const republished = (p: Planned) => sentBefore.get(p.story.id)?.sentAt !== sentAfter.get(p.story.id)?.sentAt;

      const real = (t: string) => masker.unmask(context, t).text;
      const results: FeedbackInput[] = [];
      const stale: { item: string; artifactVersion: number }[] = [];
      const rows: { line: string; value?: JiraDiffValue }[] = [];
      for (const p of planned) {
        const head = `${p.story.id} ${p.key} "${p.story.summary}"`;
        const why = p.why ?? failed.get(p.story.id) ?? (republished(p) ? "published again while comparing: run the diff again" : undefined);
        if (why || !p.sent) {
          if (p.sent) stale.push({ item: p.story.id, artifactVersion: p.sent.artifactVersion });
          rows.push({ line: `- ${head}: not compared, ${why}` });
          continue;
        }
        const issue = now.get(p.key);
        let value: JiraDiffValue = "deleted";
        let d: StoryDiff | undefined;
        if (issue) {
          // Both in clear, in memory only: the sent text with its real values put back (as
          // publishing wrote it), and Jira's. A cut text is compared with as much of Jira's.
          const jiraText = adfToText(issue.description);
          d = compareStory(
            { summary: oneLine(real(p.sent.summary)), text: real(p.sent.text), criteria: p.sent.criteria, ...(p.sent.points !== undefined && { points: p.sent.points }) },
            { summary: issue.summary, text: p.sent.truncated ? jiraText.slice(0, p.sent.text.length) : jiraText, ...(criteriaOf(issue) !== undefined && { criteria: criteriaOf(issue) }), ...(issue.points !== undefined && { points: issue.points }) },
            threshold,
          );
          value = d.value;
        }
        const facts = d
          ? [
              d.changedShare ? `${pct(d.changedShare)} of the words changed` : "",
              d.criteria[1] === undefined ? "no acceptance criteria heading left" : d.criteria[0] !== d.criteria[1] ? `acceptance criteria ${d.criteria[0]} → ${d.criteria[1]}` : "",
              d.points ? `story points ${d.points[0]} → ${d.points[1]}` : "",
              issue?.status ? `status ${STATUS[issue.status]}` : "",
            ].filter(Boolean)
          : [];
        const word = value === "deleted" ? "deleted in Jira, or no longer visible to this login" : value === "unchanged" ? "unchanged" : `${value} edit`;
        rows.push({ value, line: `- ${head}: ${word}${facts.length ? ` (${facts.join(", ")})` : ""}` });
        results.push({
          context,
          artifact: artifactId,
          artifactVersion: p.sent.artifactVersion,
          item: p.story.id,
          kind: "jira_diff",
          value,
          ...(label && { model: label }),
          ...(workflow && { workflow }),
          details: { key: p.key, ...(d && { changedShare: d.changedShare, criteria: d.criteria, ...(d.points && { points: d.points }) }), ...(issue?.status && { status: issue.status }), majorEditShare: threshold },
        });
      }
      kit.feedback.recordJiraDiff(context, artifactId, { results, stale, items: stories.map((s) => s.id) });

      const n = (v: JiraDiffValue) => rows.filter((r) => r.value === v).length;
      const compared = rows.filter((r) => r.value).length;
      const kept = compared - n("major") - n("deleted");
      const head = [
        `Jira diff of "${doc.title}" in project ${mapping.projectKey}: ${compared} of ${rows.length} published stories compared${label ? `, model label "${label}"` : ""}.`,
        `${n("unchanged")} unchanged, ${n("minor")} minor edit(s), ${n("major")} major edit(s), ${n("deleted")} deleted (major: more than ${pct(threshold)} of the words changed, or a criterion added or removed).`,
        ...(compared ? [`So far ${kept} of ${compared} (${pct(kept / compared)}) show no major edit, against the ${pct(TARGET_ACCEPTED)} target. This is a guess: people's verdicts on the review page take precedence.`] : []),
      ];
      const parts = [head.join("\n"), rows.map((r) => r.line).join("\n")];
      if (!label) parts.push('No model label is set for this context: pass model (e.g. "Opus 5.5 on Copilot") so the report can compare models.');
      return text(parts.join("\n\n"));
    }),
  );
}

const criteriaOf = (issue: JiraStory) => criteriaInAdf(issue.description);
