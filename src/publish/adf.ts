import { type Backlog, type Epic, type Story, userStoryText } from "../artifacts/backlog.js";

/** Builders for Atlassian Document Format, the rich-text format of Jira Cloud descriptions. */
type Node = Record<string, unknown>;

const txt = (text: string, bold = false): Node => (bold ? { type: "text", text, marks: [{ type: "strong" }] } : { type: "text", text });
const para = (...content: Node[]): Node => ({ type: "paragraph", content: content.filter((c) => (c.text as string)?.length !== 0) });
const heading = (text: string, level = 3): Node => ({ type: "heading", attrs: { level }, content: [txt(text)] });
const bullets = (items: string[]): Node => ({ type: "bulletList", content: items.map((i) => ({ type: "listItem", content: [para(txt(i))] })) });
const doc = (content: Node[]): Node => ({ type: "doc", version: 1, content });

export function storyDescription(story: Story, backlog: Backlog, sourceTitles: Map<string, string>): Node {
  const content: Node[] = [para(txt(userStoryText(story)))];
  content.push(heading("Acceptance criteria"));
  content.push({
    type: "orderedList",
    content: story.acceptanceCriteria.map((ac) => ({
      type: "listItem",
      content: [para(txt("Given ", true), txt(ac.given), txt(" when ", true), txt(ac.when), txt(" then ", true), txt(ac.then))],
    })),
  });
  if (story.nonFunctional?.length) content.push(heading("Non-functional requirements"), bullets(story.nonFunctional));
  if (story.technicalNotes) content.push(heading("Technical notes"), para(txt(story.technicalNotes)));
  const facts = [story.storyPoints ? `Story points: ${story.storyPoints}` : "", story.priority ? `Priority: ${story.priority}` : ""].filter(Boolean);
  if (facts.length) content.push(para(txt(facts.join(" · "))));
  content.push(...footer(backlog, story.sourceIds, sourceTitles));
  return doc(content);
}

export function epicDescription(epic: Epic, backlog: Backlog, sourceTitles: Map<string, string>): Node {
  const content: Node[] = [heading("Outcome"), para(txt(epic.outcome))];
  if (epic.successMetrics?.length) content.push(heading("Success metrics"), bullets(epic.successMetrics));
  if (epic.scopeNotes) content.push(heading("Scope"), para(txt(epic.scopeNotes)));
  content.push(...footer(backlog, epic.sourceIds, sourceTitles));
  return doc(content);
}

function footer(backlog: Backlog, sourceIds: string[] | undefined, sourceTitles: Map<string, string>): Node[] {
  const out: Node[] = [];
  if (sourceIds?.length) {
    out.push(heading("Sources", 4), bullets(sourceIds.map((id) => (sourceTitles.has(id) ? `${sourceTitles.get(id)} (${id})` : id))));
  }
  out.push({ type: "rule" }, para(txt(`Generated by sf-agent-po from backlog "${backlog.title}".`)));
  return out;
}
